// Helper functions for easy querying
export const getDestinationById = (id: string): Destination | undefined => {
  return destinations.find((d) => d.id.toLowerCase() === id.toLowerCase());
};

export const getFeaturedDestinations = (): Destination[] => {
  return destinations.filter((d) => d.featured);
};

export const getDestinationsByRegion = (region: string): Destination[] => {
  return destinations.filter((d) => d.region.toLowerCase() === region.toLowerCase());
};

export const getDestinationsByState = (stateName: string): Destination[] => {
  return destinations.filter(
    (d) => d.state.toLowerCase() === stateName.toLowerCase() || d.id.toLowerCase() === stateName.toLowerCase()
  );
};

export const getDestinationsByInterest = (interest: string): Destination[] => {
  return destinations.filter((d) =>
    d.interests.some((i) => i.toLowerCase() === interest.toLowerCase())
  );
};
